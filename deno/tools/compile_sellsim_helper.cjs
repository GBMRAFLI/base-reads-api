// Compiles contracts/SellSimHelper.sol and regenerates deno/lib/sellsim_helper.ts (solc version, source sha256, runtime bytecode).
// Needs solc-js 0.8.26 resolvable by node (e.g. `npm i solc@0.8.26` in a scratch dir, then NODE_PATH=<dir>/node_modules).
// Usage (repo root): node deno/tools/compile_sellsim_helper.cjs contracts/SellSimHelper.sol deno/lib/sellsim_helper.ts
const solc = require("solc"); const fs = require("fs"); const crypto = require("crypto");
const [srcPath, outPath] = process.argv.slice(2);
if (!srcPath || !outPath) { console.error("usage: <SellSimHelper.sol> <sellsim_helper.ts>"); process.exit(2); }
const srcBuf = fs.readFileSync(srcPath);
const out = JSON.parse(solc.compile(JSON.stringify({ language: "Solidity", sources: { "SellSimHelper.sol": { content: srcBuf.toString("utf8") } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun", outputSelection: { "*": { "*": ["evm.deployedBytecode.object"] } } } })));
let fatal = false; for (const e of out.errors ?? []) { console.error(e.formattedMessage); if (e.severity === "error") fatal = true; }
if (fatal) process.exit(1);
const runtime = "0x" + out.contracts["SellSimHelper.sol"].SellSimHelper.evm.deployedBytecode.object;
fs.writeFileSync(outPath, `// GENERATED by deno/tools/compile_sellsim_helper.cjs from contracts/SellSimHelper.sol. Do not edit by hand.
// Runtime bytecode only: it is injected with an eth_call code override and never deployed.
export const HELPER_SOLC = ${JSON.stringify(solc.version())};
export const HELPER_SOURCE_SHA256 = ${JSON.stringify(crypto.createHash("sha256").update(srcBuf).digest("hex"))};
export const HELPER_RUNTIME = ${JSON.stringify(runtime)};
`);
console.error("wrote " + outPath);
